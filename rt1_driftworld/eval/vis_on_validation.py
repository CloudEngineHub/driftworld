"""
Visualize the videos generated by DriftWorld.
The input json file determines which episodes are selected, so that the same episodes are generated on every run of this file.
"""
import os
import json
import random
import logging
from pathlib import Path

import torch
from torch.utils.data import DataLoader, Subset

from datasets.dataset_precomputed import OpenXMP4PrecomputedDataset
from datasets.rt1_dataloader import _pad_collate_full_video
from encoders.vae_utils import decode_latents
from encoders.vae_sd3 import VAE
from utils.eval_utils import set_seed, setup_model, save_video, gen_helper

log = logging.getLogger(__name__)


def _default_selection_file(split, n_videos):
    """
    Fixed repo path for the episode selection json.
    """
    pkg_root = Path(__file__).resolve().parent.parent
    return str(pkg_root / f"vis_on_validation_selection_{split}_{n_videos}.json")


def vis_on_validation(cfg, n_videos=64, use_ema=True, step=None, fps=4, split="val",
                      chunk_size=16, use_autoregressive=False, batch_size=4, cfg_scale=None,
                      save_gt=True, selection_seed=0, selection_file=None):
    """
    Generate full-length videos for a fixed random subset of the validation set.

    Args:
        cfg: Hydra config.
        n_videos: number of validation videos in the fixed subset
        use_ema: whether to use EMA model
        step: checkpoint step to load (None = latest)
        fps: frames per second for saved mp4s
        split: dataset split
        chunk_size: VAE decode chunk size
        use_autoregressive: whether to do autoregressive generation
        batch_size: number of videos per batch
        cfg_scale: optional action CFG scale
        save_gt: if True, also decode + save the ground-truth mp4 for each video
        selection_seed: RNG seed used the FIRST time the subset is sampled
        selection_file: path to the JSON file recording the selected video filenames
    """
    log.info(f"Using dataset dir: {cfg.rt1.dataset_dir}")

    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    log.info(f"Visualization on the {split} split (n_videos={n_videos})")
    set_seed(cfg.train.seed)

    log.info("Using SD3 VAE")
    vae = VAE().to(device)

    # Build the full-video dataset
    dataset = OpenXMP4PrecomputedDataset(
        save_dir=cfg.rt1.dataset_dir,
        n_frames=cfg.rt1.n_frames,
        action_dim=cfg.rt1.action_dim,
        subset_names=cfg.rt1.subset_names,
        split=split,
        input_h=cfg.rt1.input_h,
        input_w=cfg.rt1.input_w,
        full_video=True,
    )

    stems = [p.stem for p in dataset.video_paths]
    stem_to_idx = {stem: i for i, stem in enumerate(stems)}

    # json file to select episodes
    if selection_file is None:
        selection_file = _default_selection_file(split, n_videos)

    if os.path.exists(selection_file):
        with open(selection_file, "r") as f:
            selected_stems = json.load(f)
        log.info(f"Loaded {len(selected_stems)} selected video stems from {selection_file}")
    else:
        if n_videos > len(stems):
            raise ValueError(
                f"Requested n_videos={n_videos} but the {split} split only has {len(stems)} videos"
            )
        rng = random.Random(selection_seed)
        selected_stems = sorted(rng.sample(stems, n_videos))
        os.makedirs(os.path.dirname(selection_file), exist_ok=True)
        with open(selection_file, "w") as f:
            json.dump(selected_stems, f, indent=2)
        log.info(f"Sampled {len(selected_stems)} video stems (seed={selection_seed}) and "
                 f"saved them to {selection_file}")

    # Map selected stems -> dataset indices
    selected_indices, ordered_stems = [], []
    for stem in selected_stems:
        if stem not in stem_to_idx:
            log.warning(f"Selected video '{stem}' not found in the current {split} dataset; skipping")
            continue
        selected_indices.append(stem_to_idx[stem])
        ordered_stems.append(stem)
    log.info(f"Using {len(selected_indices)}/{len(selected_stems)} selected videos present in the dataset")

    subset = Subset(dataset, selected_indices)
    dataloader = DataLoader(
        subset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=cfg.dataloader.num_workers,
        collate_fn=_pad_collate_full_video,
        pin_memory=cfg.dataloader.pin_memory,
    )

    denoiser, actual_step = setup_model(cfg, step)

    folder_root = f"{cfg.output_dir}/vis_on_validation"
    os.makedirs(folder_root, exist_ok=True)
    gt_root = f"{folder_root}/gt"
    if save_gt:
        os.makedirs(gt_root, exist_ok=True)

    cfg_tag = "" if cfg_scale is None else f"_cfg{cfg_scale}"

    # Subset preserves order and shuffle=False
    processed = 0
    for i, batch in enumerate(dataloader):
        log.info(f"(batch {i}/{len(dataloader)}) start | lengths {batch['lengths'].tolist()}")

        batch['video_latents'] = vae.encode(batch['video'].to(device))

        gen = gen_helper(denoiser, batch, use_ema, use_autoregressive=use_autoregressive, cfg_scale=cfg_scale)

        gt_pixels = None
        if save_gt:
            gt_latents = batch['video_latents'].to(device)
            gt_pixels = decode_latents(gt_latents, vae=vae.vae, chunk_size=chunk_size).cpu()

        lengths = batch['lengths']
        B = gen.shape[0]
        for j in range(B):
            stem = ordered_stems[processed]
            L = int(lengths[j])

            if not use_autoregressive:
                gen_path = f"{folder_root}/{stem}_step{actual_step}_ema{use_ema}{cfg_tag}_len{L}.mp4"
            else:
                gen_path = f"{folder_root}/{stem}_step{actual_step}_ema{use_ema}{cfg_tag}_len{L}_autoregressive.mp4"

            save_video(gen[j][:L], gen_path, fps=fps, value_range=(-1, 1))
            log.info(f"saved predicted video at {gen_path}")

            if save_gt:
                gt_path = f"{gt_root}/{stem}_gt_len{L}.mp4"
                if os.path.exists(gt_path):
                    log.info(f"GT video already exists, skipping: {gt_path}")
                else:
                    save_video(gt_pixels[j][:L], gt_path, fps=fps, value_range=(-1, 1))
                    log.info(f"saved ground-truth video at {gt_path}")

            processed += 1

    log.info(f"Done. Generated {processed} videos under {folder_root}")
